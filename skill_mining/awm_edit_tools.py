def render_id_instructions(files):
    """Use only real current IDs in format examples; no stale literal hashes."""
    catalog = build_edit_catalog(files)
    examples = []
    for name in EDITABLE_FILES:
        first = next((key for key, row in catalog.items() if row["file"] == name), None)
        if first:
            examples.append(f'{name}: display [{first}] -> EDIT '
                            + json.dumps({"target_id": first, "op": "replace"}))
    result = ID_TOOL_INSTRUCTIONS + "\nCurrent snapshot metadata header examples (NOT suggested edits):\n" + "\n".join(examples)
    # Complete examples are essential: an ID-only fragment is not an edit schema.
    # Use real IDs and unchanged snapshot text, never stale example revisions.
    candidates = [(key, row) for key, row in catalog.items()
                  if not row["blank"] and row["text"] not in {"END_EDIT", "END_PLAN"}]
    if candidates:
        key, row = min(candidates, key=lambda item: (item[1]["text"].startswith("#"), len(item[1]["text"])))
        result += "\n\n## Complete Format Examples (independent examples, NOT proposed edits)\n"
        for op in ("replace", "insert_before", "insert_after", "delete"):
            # The replacement demonstrates a harmless unchanged line; insert/delete
            # examples demonstrate syntax only and are never submitted by Python.
            body = "" if op == "delete" else row["text"] + "\n"
            result += (f"Example {op}:\nAWM_EDIT_PLAN_V1\nEDIT "
                       + json.dumps({"target_id": key, "op": op}) + "\n" + body
                       + "END_EDIT\nEND_PLAN\n")
    return result


def id_validation_feedback(catalog, name, target, field):
    """Explicit reselection hints only. Never correct an ID automatically."""
    row = catalog.get(target)
    rows = [(key, value) for key, value in catalog.items() if value["file"] == name]
    match = re.fullmatch(r"([0-9a-f]{16}):L([1-9][0-9]*)", target)
    if name is not None and name not in EDITABLE_FILES:
        reason = "invalid_file"
    elif row is not None:
        reason = "valid" if row["file"] == name else "wrong_file"
    elif match is None:
        reason = "malformed_id"
    elif any(key.startswith(match[1] + ":") for key, _ in rows):
        reason = "line_not_addressable_in_current_file"
    else:
        reason = "unknown_revision"
    same_line = [key for key, value in rows if match and value["line"] == int(match[2])]
    return {"field": field, "requested_id": target, "reason": reason,
            "supplied_file": name, "file_is_optional_with_current_id": True,
            "actual_file": row["file"] if row else None,
            "current_file_revision": rows[0][0].split(":", 1)[0] if rows else None,
            "same_line_number_candidates_not_auto_applied": same_line,
            "current_heading_ids": [key for key, value in rows
                                    if re.match(r"^#{1,6}\s", value["text"])][:24]}


def normalize_target_id(value):
    """Accept one catalog display wrapper, never fuzzy-match or drop revisions."""
    if isinstance(value, str):
        match = re.fullmatch(r"\[([0-9a-f]{16}:L[1-9][0-9]*)\]", value)
        if match:
            return match[1]
    return value


def resolve_edit_file(supplied, first, last):
    """Infer only from EXACT current IDs. Never guess a stale ID or wrong file."""
    if supplied is None or isinstance(supplied, str) and not supplied.strip():
        return first["file"] if first and last and first["file"] == last["file"] else None
    if isinstance(supplied, str):
        # Accept literal display quoting/spacing, not arbitrary path basenames,
        # aliases, typo correction or redirection to another writable resource.
        name = supplied.strip()
        if len(name) >= 2 and name[0] == name[-1] == "`":
            name = name[1:-1]
        if name.startswith("./"):
            name = name[2:]
        if name in EDITABLE_FILES:
            return name
    return supplied


def _resolve_id_plan(plan, files):
    catalog, spans = build_edit_catalog(files), []
    for index, operation in enumerate(plan["operations"], 1):
        if not isinstance(operation, dict) or set(operation) - {
            "file", "target_id", "end_target_id", "op", "new_text", "section", "rationale"}:
            raise AWMEditError(f"Edit {index}: do not mix ID addressing and old match_text fields")
        first_id = normalize_target_id(operation.get("target_id"))
        end_id = operation.get("end_target_id")
        last_id = normalize_target_id(operation.get("target_id") if end_id is None else end_id)
        if not isinstance(first_id, str) or not isinstance(last_id, str):
            raise AWMEditError(f"Edit {index}: target IDs must be strings")
        first, last = catalog.get(first_id), catalog.get(last_id)
        name = resolve_edit_file(operation.get("file"), first, last)
        if first is None or last is None or first["file"] != name or last["file"] != name:
            details = [id_validation_feedback(catalog, name, first_id, "target_id")]
            if "end_target_id" in operation:
                details.append(id_validation_feedback(catalog, name, last_id, "end_target_id"))
            summary = "; ".join(f"{item['field']}={item['requested_id']} ({item['reason']})"
                                for item in details if item["reason"] != "valid")
            raise AWMEditError(f"Edit {index}: unknown/stale target_id or wrong file: {summary}; supplied_file={operation.get('file')!r}, actual_file={first['file'] if first else None!r}; explicitly reselect from current snapshot",
                {"edit_index": index, "file": name, "target_id": first_id,
                 "end_target_id": last_id, "target_present": first is not None,
                 "end_target_present": last is not None,
                 "actual_file": first["file"] if first else None,
                 "address_checks": details,
                 "instruction": "Omit file metadata; valid current target_id/end_target_id uniquely determine the file. Inspect the current snapshot content and explicitly reselect intended start/end IDs. Never guess or reuse stale IDs. Explicit conflicting file metadata is not ignored."})
        start, end = first["start"], last["end"]
        if start >= end:
            raise AWMEditError(f"Edit {index}: reversed/empty target range")
        if any(n == name and start < e and end > s for n, s, e, _, _ in spans):
            raise AWMEditError(f"Edit {index}: overlapping targets; merge them into one edit")
        source = files[name]
        anchor = source[start:end]
        positions = [m.start() for m in re.finditer(re.escape(anchor), source)]
        if start not in positions:
            raise AWMEditError(f"Edit {index}: selected span cannot be represented as a nonoverlapping text anchor")
        converted = {k: v for k, v in operation.items() if k not in {"target_id", "end_target_id"}}
        # Blank rows include their newline in the exact anchor (needed for a
        # meaningful delete). For other operations retain that boundary instead
        # of rejecting the row or silently joining neighboring prose.
        op, replacement = operation.get("op"), operation.get("new_text")
        boundary = (last if op in {"replace", "insert_after"} else first)
        if op in {"replace", "insert_before", "insert_after"} and boundary["blank"]:
            if not isinstance(replacement, str) or not replacement:
                raise AWMEditError(f"Edit {index}: missing/non-text or empty new_text")
            ending = boundary["line_ending"]
            if op == "replace":
                if ending and not replacement.endswith(("\n", "\r")):
                    replacement += ending
            else:
                separator = ending or ("\r\n" if "\r\n" in source else "\n")
                if not replacement.endswith(("\n", "\r")):
                    replacement += separator
                if op == "insert_after" and not ending:
                    replacement = separator + replacement
            converted["new_text"] = replacement
        converted.update(file=name, match_text=anchor, occurrence=positions.index(start) + 1)
        spans.append((name, start, end, converted, index - 1))
    # Reverse offsets preserve every original location despite earlier edits.
    spans.sort(key=lambda item: (item[0], item[1]), reverse=True)
    converted = {"operations": [item[3] for item in spans]}
    return converted, [(item[4], plan["operations"][item[4]]) for item in spans]


class AWMEditError(ValueError):
    def __init__(self, message, repair_context=None):
        super().__init__(message)
        self.repair_context = repair_context or {}


def anchor_repair_context(source, anchor, positions, occurrence):
    """Suggest literal current-file excerpts; NEVER use similarity for writing."""
    candidates = []
    if positions:
        for number, position in enumerate(positions[:6], 1):
            candidates.append({"occurrence": number,
                "surrounding_text": source[max(0, position - 180):position + min(len(anchor), 400) + 180]})
    else:
        lines = [(m.start(), m.group(0)) for m in re.finditer(r"(?m)^.+$", source) if m.group(0).strip()]
        ranked = sorted(lines, key=lambda item: SequenceMatcher(None, anchor[:1000], item[1][:1000], autojunk=False).ratio(), reverse=True)
        seen = set()
        for position, line in ranked:
            snippet = line[:600]
            if snippet in seen:
                continue
            seen.add(snippet)
            candidates.append({"match_text": snippet, "exact_match_count": source.count(snippet),
                               "line": source[:position].count("\n") + 1})
            if len(candidates) == 4:
                break
    return {"exact_match_count": len(positions), "requested_occurrence": occurrence,
            "anchor_preview": anchor[:300], "literal_candidates": candidates,
            "instruction": "These are current-file excerpts for explicit reselection, not applied replacements. Copy exact text, preserve intent, and provide occurrence when repeated."}

