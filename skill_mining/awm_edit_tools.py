def parse_edit_response(raw):
    """Decode only COMPLETE plans. Never repair JSON or salvage partial operations."""
    text = raw.strip()
    if text.startswith("AWM_EDIT_PLAN_V1"):
        lines = text.splitlines(keepends=True)
        if lines[0].strip() != "AWM_EDIT_PLAN_V1" or lines[-1].strip() != "END_PLAN":
            raise AWMEditResponseError("Incomplete raw-text edit plan: require header and final END_PLAN")
        operations = []
        cursor = 1
        while cursor < len(lines) - 1:
            header = lines[cursor].rstrip("\r\n")
            if not header.startswith("EDIT "):
                raise AWMEditResponseError("Expected EDIT metadata, not commentary or an unfinished body")
            metadata = json.loads(header[5:])
            if not isinstance(metadata, dict) or set(metadata) - {"file", "target_id", "end_target_id", "op"}:
                raise AWMEditResponseError("Raw-text metadata accepts file, target_id, end_target_id, op only")
            cursor += 1
            body = []
            while cursor < len(lines) - 1 and lines[cursor].rstrip("\r\n") != "END_EDIT":
                if lines[cursor].rstrip("\r\n") == "END_PLAN":
                    raise AWMEditResponseError("Missing END_EDIT before END_PLAN")
                body.append(lines[cursor])
                cursor += 1
            if cursor >= len(lines) - 1:
                raise AWMEditResponseError("Incomplete raw-text edit: missing END_EDIT; no edits applied")
            value = "".join(body)
            if value.endswith("\r\n"):
                value = value[:-2]
            elif value.endswith("\n") or value.endswith("\r"):
                value = value[:-1]
            operations.append({**metadata, "new_text": value})
            cursor += 1
        plan = {"operations": operations}
    else:
        if text.startswith("```"):
            text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.I | re.S).strip()
        plan = json.loads(text)
    if not isinstance(plan, dict) or set(plan) != {"operations"} or not isinstance(plan["operations"], list):
        raise ValueError('Expected {"operations":[...]} edit plan only')
    return plan


def validate_edit_plan_structure(plan):
    """Collect ALL required-field errors before sorting or simulating any edits.

    Decoding remains backward-compatible; this preflight is used by induction.
    Missing op is never inferred from new_text, IDs, or neighboring operations.
    """
    allowed_ops = ("replace", "insert_before", "insert_after", "delete")
    if not isinstance(plan, dict) or set(plan) != {"operations"} or not isinstance(plan["operations"], list):
        raise AWMEditError('Expected an edit plan with an operations list',
                           {"error_kind": "edit_plan_structure", "instruction": "Return a complete AWM_EDIT_PLAN_V1 plan."})
    issues = []
    id_addressing = (any(isinstance(edit, dict) and "target_id" in edit for edit in plan["operations"])
                     or not all(isinstance(edit, dict) and "file" in edit and "match_text" in edit
                                for edit in plan["operations"]))
    for index, edit in enumerate(plan["operations"], 1):
        if not isinstance(edit, dict):
            issues.append({"edit_index": index, "field": "edit", "reason": "non_object", "actual_type": type(edit).__name__})
            continue

        def issue(field, reason, **extra):
            issues.append({"edit_index": index, "field": field, "reason": reason,
                           "actual_type": type(edit.get(field)).__name__,
                           "target_id": edit.get("target_id") if isinstance(edit.get("target_id"), str) else None,
                           **extra})

        op = edit.get("op")
        if "op" not in edit:
            issue("op", "missing", allowed_values=list(allowed_ops))
        elif not isinstance(op, str):
            issue("op", "non_text", allowed_values=list(allowed_ops))
        elif op not in allowed_ops:
            issue("op", "invalid_value", allowed_values=list(allowed_ops))
        if id_addressing:
            if "target_id" not in edit:
                issue("target_id", "missing")
            elif not isinstance(edit["target_id"], str) or not edit["target_id"].strip():
                issue("target_id", "non_text_or_empty")
            end = edit.get("end_target_id")
            if end is not None and (not isinstance(end, str) or not end.strip()):
                issue("end_target_id", "non_text_or_empty")
        else:
            for field in ("file", "match_text"):
                if field not in edit:
                    issue(field, "missing")
                elif not isinstance(edit[field], str) or not edit[field].strip():
                    issue(field, "non_text_or_empty")
        if "new_text" not in edit:
            if op != "delete":
                issue("new_text", "missing")
        elif not isinstance(edit["new_text"], str):
            issue("new_text", "non_text")
        elif op == "delete" and edit["new_text"]:
            issue("new_text", "delete_body_must_be_empty")
    if issues:
        summary = "; ".join(f"Edit {item['edit_index']}: {item['reason']} {item['field']}" for item in issues)
        raise AWMEditError("Invalid edit-plan structure: " + summary, {
            "error_kind": "edit_plan_structure", "structure_issues": issues,
            "operation_count": len(plan["operations"]), "validated_prefix_edits": 0,
            "instruction": "Fix EVERY listed field error, not only the first. Each EDIT header MUST include an explicit string op chosen from replace/insert_before/insert_after/delete and a current target_id. Choose op according to your intended edit; never omit it, infer a default, or copy another edit's op blindly. Put literal text in the body, not a new_text metadata field. Return one COMPLETE corrected AWM_EDIT_PLAN_V1 plan. Nothing has been applied."})
    return plan


def apply_awm_edit_plan(raw, files, valid_actions):
    """Parse/validate/apply atomically in memory; caller checkpoints the bundle."""
    from skill_mining.online_refinement import apply_dynamic_skill_operations
    plan = parse_edit_response(raw)
    id_mapping = None
    if any(isinstance(op, dict) and "target_id" in op for op in plan["operations"]):
        plan, id_mapping = _resolve_id_plan(plan, files)
    current = {name: files[name] for name in EDITABLE_FILES}
    outcomes = []
    for index, operation in enumerate(plan["operations"], 1):
        display_index = id_mapping[index - 1][0] + 1 if id_mapping is not None else index
        delete_text_defaulted = False
        try:
            if not isinstance(operation, dict) or set(operation) - {
                "file", "section", "op", "match_text", "new_text", "rationale", "occurrence"}:
                raise ValueError("unsupported edit fields")
            if operation.get("op") == "delete" and "new_text" not in operation:
                operation = {**operation, "new_text": ""}
                delete_text_defaulted = True
            for key in ("file", "op", "match_text", "new_text"):
                if not isinstance(operation.get(key), str):
                    raise ValueError(f"missing/non-text {key}")
            name = operation["file"]
            if name not in EDITABLE_FILES:
                raise ValueError("file is not writable")
            section_hint = operation.get("section")
            anchor = operation["match_text"]
            if not anchor:
                raise ValueError("match_text must be nonempty")
            source = current[name]
            occurrences = [m.start() for m in re.finditer(re.escape(anchor), source)]
            occurrence = operation.get("occurrence", 1)
            if not occurrences:
                raise AWMEditError("anchor missing: 0 exact matches; copy literal current-file text",
                    anchor_repair_context(source, anchor, occurrences, operation.get("occurrence")))
            if len(occurrences) > 1 and "occurrence" not in operation:
                raise AWMEditError(f"anchor ambiguous: {len(occurrences)} exact matches; supply a 1-based occurrence or a longer unique excerpt",
                    anchor_repair_context(source, anchor, occurrences, None))
            if type(occurrence) is not int or not 1 <= occurrence <= len(occurrences):
                raise AWMEditError(f"invalid occurrence: {occurrence!r}; expected 1..{len(occurrences)}",
                    anchor_repair_context(source, anchor, occurrences, occurrence))
            position = occurrences[occurrence - 1]
            # Headings are descriptive, not a second fragile addressing scheme.
            # Resolve the hierarchy from the EXACT selected anchor, never fuzzy
            # match model-authored section names or guess a missing text anchor.
            heading_path = []
            for heading in re.finditer(r"(?m)^(#{1,6})[ \t]+[^\n]+", source):
                if heading.start() > position:
                    break
                depth = len(heading[1])
                while heading_path and heading_path[-1][0] >= depth:
                    heading_path.pop()
                heading_path.append((depth, heading[0].strip()))
            section = heading_path[-1][1] if heading_path else "<document>"
            warnings = []
            if delete_text_defaulted:
                warnings.append("delete_new_text_defaulted_empty")
            if not isinstance(section_hint, str) or not section_hint.strip():
                warnings.append("section_inferred")
            elif section_hint != "<document>" and not any(
                section_hint.strip() in {h, re.sub(r"^#{1,6}\s+", "", h)} for _, h in heading_path
            ):
                warnings.append("section_hint_mismatch_exact_anchor_used")
            normalized = dict(operation)
            if not isinstance(operation.get("rationale"), str) or not operation["rationale"].strip():
                normalized["rationale"] = ""
                warnings.append("rationale_missing")
            updated, records = apply_dynamic_skill_operations(source, [normalized])
            if records[0].get("error") or not records[0].get("applied"):
                raise ValueError(str(records[0].get("error") or "edit was not applied"))
            if name != "skill.md":
                before = re.findall(r"(?m)^####\s+`([^`]+)`\s*$", source)
                after = re.findall(r"(?m)^####\s+`([^`]+)`\s*$", updated)
                for action in set(after):
                    if action not in valid_actions and action not in before:
                        raise ValueError("new card heading is not a canonical action")
                    if after.count(action) > max(1, before.count(action)):
                        heading_ids = [key for key, row in build_edit_catalog(files).items()
                                       if row["file"] == name and re.fullmatch(
                                           r"####\s+`" + re.escape(action) + r"`\s*", row["text"])]
                        raise AWMEditError("edit creates duplicate action cards", {
                            "action": action, "before_heading_count": before.count(action),
                            "after_heading_count": after.count(action),
                            "existing_card_heading_ids": heading_ids,
                            "instruction": "A body-only edit must not repeat the card heading. For a complete card replacement, explicitly target its existing heading through its last body line, excluding the next card heading. Do not add another copy."})
            current[name] = updated
            outcomes.append({**records[0], "file": name, "section": section,
                             "section_hint": section_hint, "section_path": [h for _, h in heading_path],
                             "warnings": warnings})
        except Exception as exc:
            context = {**getattr(exc, "repair_context", {}), "edit_index": display_index,
                       "execution_index": index,
                       "file": operation.get("file", "?") if isinstance(operation, dict) else "?",
                       "validated_prefix_edits": index - 1,
                       "note": "Earlier operations were simulated only; the whole rejected plan was NOT committed."}
            raise AWMEditError(f"Edit {display_index} ({context['file']}): {exc}", context) from exc
    if not current["skill.md"].strip():
        raise ValueError("Edit plan erased the entire workflow")
    if id_mapping is not None:
        for record, (index, original) in zip(outcomes, id_mapping):
            record.update(target_id=original["target_id"], end_target_id=original.get("end_target_id"), plan_index=index)
            if original.get("file") != record["file"]:
                record["supplied_file"] = original.get("file")
                record["warnings"].append("file_resolved_from_current_target_id")
            if "new_text" in original and record.get("new_text") != original["new_text"]:
                record["plan_new_text"] = original["new_text"]
                record["warnings"].append("blank_line_boundary_normalized")
        outcomes.sort(key=lambda row: row["plan_index"])
    return current, outcomes
